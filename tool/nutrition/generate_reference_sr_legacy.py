#!/usr/bin/env python3
"""Extract an audited public-domain USDA SR Legacy subset to a Dart part."""

import argparse
import csv
import hashlib
import io
import json
import sys
import zipfile
from collections import defaultdict
from decimal import Decimal
from pathlib import Path

ARCHIVE_SHA256 = "b80817294b8850530aaedf2e515c02593b1824f763a0ff356e5c2081643e6fd0"
ROOT = Path(__file__).resolve().parents[2]
SELECTION = Path(__file__).with_name("reference_sr_legacy_selection.tsv")
OUTPUT = ROOT / "lib/nutrition/reference_sr_legacy_data.dart"
NUTRIENTS = {
    "1008": ("energy", "KCAL"),
    "1003": ("protein", "G"),
    "1005": ("carbohydrates", "G"),
    "1004": ("fat", "G"),
    "1079": ("fibre", "G"),
    "2000": ("totalSugars", "G"),
    "1087": ("calcium", "MG"),
    "1089": ("iron", "MG"),
    "1090": ("magnesium", "MG"),
    "1092": ("potassium", "MG"),
    "1093": ("sodium", "MG"),
    "1162": ("vitaminC", "MG"),
    "1114": ("vitaminD", "UG"),
    "1177": ("folate", "UG"),
    "1178": ("vitaminB12", "UG"),
}


def table(archive, name):
    path, = [path for path in archive.namelist() if path.endswith(f"/{name}.csv")]
    with archive.open(path) as content:
        yield from csv.DictReader(io.TextIOWrapper(content, encoding="utf-8-sig", newline=""))


def number(value):
    parsed = Decimal(value)
    if not parsed.is_finite() or parsed < 0:
        raise ValueError(f"Invalid source value {value!r}")
    return format(parsed, "f")


def string(value):
    return json.dumps(value, ensure_ascii=False).replace("$", r"\$")


def integer_or_null(value):
    return str(int(value)) if value else "null"


def string_or_null(value):
    return string(value) if value else "null"


def archive_digest(path):
    checksum = hashlib.sha256()
    with path.open("rb") as source:
        while chunk := source.read(1024 * 1024):
            checksum.update(chunk)
    return checksum.hexdigest()


def render(archive):
    with SELECTION.open(encoding="utf-8", newline="") as selection:
        selected = list(csv.DictReader(selection, delimiter="\t"))
    ids = {row["fdc_id"] for row in selected}
    names = {row["name"] for row in selected}
    if len(ids) != len(selected) or len(names) != len(selected):
        raise ValueError("Selection contains repeated IDs or display names")

    foods = {row["fdc_id"]: row for row in table(archive, "food") if row["fdc_id"] in ids}
    ndb = {
        row["fdc_id"]: row["NDB_number"]
        for row in table(archive, "sr_legacy_food")
        if row["fdc_id"] in ids
    }
    derivations = {row["id"]: row["code"] for row in table(archive, "food_nutrient_derivation")}
    measures = {row["id"]: row["name"] for row in table(archive, "measure_unit")}
    units = {row["id"]: row["unit_name"] for row in table(archive, "nutrient")}
    if any(units.get(key) != expected for key, (_, expected) in NUTRIENTS.items()):
        raise ValueError("Unexpected nutrient units in archive")

    nutrients = defaultdict(dict)
    for row in table(archive, "food_nutrient"):
        key = row["fdc_id"]
        nutrient = row["nutrient_id"]
        if key not in ids or nutrient not in NUTRIENTS or not row["amount"]:
            continue
        if nutrient in nutrients[key]:
            raise ValueError(f"Ambiguous nutrient {nutrient} for food {key}")
        nutrients[key][nutrient] = row

    portions = defaultdict(list)
    seen_portions = set()
    for row in table(archive, "food_portion"):
        key = row["fdc_id"]
        if key not in ids or not row["amount"] or not row["gram_weight"]:
            continue
        if Decimal(number(row["amount"])) == 0 or Decimal(number(row["gram_weight"])) == 0:
            continue
        if row["id"] in seen_portions:
            raise ValueError(f"Duplicate portion ID {row['id']}")
        seen_portions.add(row["id"])
        portions[key].append(row)

    lines = [
        "// Generated by tool/nutrition/generate_reference_sr_legacy.py.",
        "// USDA FoodData Central, SR Legacy April 2018. CC0 1.0.",
        "// dart format off",
        "part of 'reference_food_catalog.dart';",
        "",
        "const _srLegacyFoods = <ReferenceFood>[",
    ]
    for item in selected:
        key = item["fdc_id"]
        food = foods.get(key)
        if not food or food["data_type"] != "sr_legacy_food" or key not in ndb:
            raise ValueError(f"Expected a real SR Legacy food for ID {key}")
        aliases = [value.strip() for value in item["aliases"].split(";") if value.strip()]
        lines.extend([
            "  ReferenceFood._(",
            f"    fdcId: {int(key)},",
            f"    ndbNumber: {string(ndb[key])},",
            f"    name: {string(item['name'])},",
            f"    officialDescription: {string(food['description'])},",
            f"    group: ReferenceFoodGroup.{item['group']},",
            f"    aliases: [{', '.join(map(string, aliases))}],",
            "    composition: {",
        ])
        for nutrient, (enum_name, _) in NUTRIENTS.items():
            row = nutrients[key].get(nutrient)
            if row is None:
                continue
            code = derivations.get(row["derivation_id"])
            lines.append(
                f"      ReferenceNutrient.{enum_name}: ReferenceNutrientValue("
                f"{number(row['amount'])}, {int(row['id'])}, "
                f"{integer_or_null(row['data_points'])}, {string_or_null(code)}),"
            )
        lines.extend(["    },", "    measures: ["])
        for row in sorted(portions[key], key=lambda row: (int(row["seq_num"] or 0), int(row["id"]))):
            unit = measures[row["measure_unit_id"]]
            lines.append(
                f"      ReferenceFoodMeasure({int(row['id'])}, {number(row['amount'])}, "
                f"{number(row['gram_weight'])}, {string(unit)}, "
                f"{string_or_null(row['portion_description'])}, {string_or_null(row['modifier'])}, "
                f"{integer_or_null(row['data_points'])}),"
            )
        lines.extend(["    ],", "  ),"])
    return "\n".join([*lines, "];", ""])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("archive", type=Path, help="Pinned USDA SR Legacy April 2018 CSV ZIP")
    parser.add_argument("--check", action="store_true", help="Verify the checked-in extraction")
    args = parser.parse_args()
    if archive_digest(args.archive) != ARCHIVE_SHA256:
        parser.error("Archive SHA-256 differs from the pinned USDA release")
    with zipfile.ZipFile(args.archive) as archive:
        output = render(archive)
    if args.check:
        if OUTPUT.read_text(encoding="utf-8") != output:
            parser.error("The checked-in extraction does not match the pinned source")
    else:
        OUTPUT.write_text(output, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    sys.exit(main())
